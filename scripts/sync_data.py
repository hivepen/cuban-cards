#!/usr/bin/env python3
"""Sincroniza el catálogo desde qvapay/cuban_cards_prefixes fijando versión.

Uso:
    python3 scripts/sync_data.py --version v0.5.2

Descarga prefixes.json y validators.json de ese tag del upstream, los deja
en data/, copia ambos a python/src/cuban_cards/data/, regenera
dart/lib/src/data.g.dart y corre las pruebas de conformidad de Python.
Solo biblioteca estándar.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://raw.githubusercontent.com/qvapay/cuban_cards_prefixes/{tag}/{name}"


def fetch(tag: str, name: str) -> str:
    url = BASE.format(tag=tag, name=name)
    with urllib.request.urlopen(url) as r:  # noqa: S310 - URL fija de GitHub
        return r.read().decode("utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True, help="Tag del upstream, p. ej. v0.5.2")
    args = ap.parse_args()

    prefixes = fetch(args.version, "prefixes.json")
    validators = fetch(args.version, "validators.json")
    version = json.loads(prefixes)["version"]
    if json.loads(validators)["version"] != version:
        print("Error: prefixes.json y validators.json no comparten versión", file=sys.stderr)
        return 1

    (ROOT / "data" / "prefixes.json").write_text(prefixes, encoding="utf-8")
    (ROOT / "data" / "validators.json").write_text(validators, encoding="utf-8")

    py_data = ROOT / "python" / "src" / "cuban_cards" / "data"
    (py_data / "prefixes.json").write_text(prefixes, encoding="utf-8")
    (py_data / "validators.json").write_text(validators, encoding="utf-8")

    dart = (
        "// GENERATED by scripts/sync_data.py — do not edit by hand.\n"
        "// Catalog data from qvapay/cuban_cards_prefixes (MIT), vendored pinned.\n"
        "// ignore_for_file: type=lint\n\n"
        "const String kPrefixesJson = r'''\n" + prefixes.rstrip("\n") + "\n''';\n\n"
        "const String kValidatorsJson = r'''\n" + validators.rstrip("\n") + "\n''';\n"
    )
    (ROOT / "dart" / "lib" / "src" / "data.g.dart").write_text(dart, encoding="utf-8")

    up = ROOT / "data" / "UPSTREAM.md"
    text = up.read_text(encoding="utf-8")
    import re

    text = re.sub(r"v\d+\.\d+\.\d+ \(`\"version\": \"\d+\.\d+\.\d+\"`\)", f'{args.version} (`"version": "{version}"`)', text)
    up.write_text(text, encoding="utf-8")

    print(f"Datos sincronizados a la versión {version} del upstream.")
    print("Corriendo conformidad de Python…")
    r = subprocess.run(
        [sys.executable, "-m", "unittest", "discover", "-s", "tests"],
        cwd=ROOT / "python",
        env={"PYTHONPATH": "src", "PATH": "/usr/bin:/bin:/usr/local/bin"},
    )
    return r.returncode


if __name__ == "__main__":
    raise SystemExit(main())
